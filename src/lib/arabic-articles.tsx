// ============ Article 3: Prompt Engineering ============
function PromptArticle() {
  return (
    <>
      <P>
        هندسة الأوامر (Prompt Engineering) هي فن وعلم صياغة التعليمات للنماذج اللغوية الكبيرة
        للحصول على أفضل النتائج. الفرق بين أمر مبهم وأمر محكم قد يعني الفرق بين إجابة عديمة
        الفائدة وحل احترافي جاهز للاستخدام.
      </P>

      <H2 id="role">١. حدّد الدور (Role)</H2>
      <P>
        أخبر النموذج من يكون قبل أن تطلب منه شيئاً. «أنت مطوّر React خبير بعشر سنوات خبرة» يُنتج
        إجابة مختلفة تماماً عن سؤال مباشر بدون سياق.
      </P>

      <H2 id="context">٢. قدّم السياق</H2>
      <P>
        كلما زاد السياق ذو الصلة، تحسّنت الإجابة. اذكر: نوع المشروع، الجمهور المستهدف، القيود
        التقنية، والهدف النهائي.
      </P>
      <H3>مثال ضعيف مقابل قوي</H3>
      <P>
        <strong>ضعيف:</strong> «اكتب لي كود تسجيل دخول».
      </P>
      <P>
        <strong>قوي:</strong> «اكتب مكوّن React Server Component لتسجيل الدخول باستخدام
        Supabase Auth، مع تحقق Zod ورسائل خطأ عربية».
      </P>

      <H2 id="examples">٣. استخدم الأمثلة (Few-shot Prompting)</H2>
      <P>
        تقديم مثال أو مثالين على المخرجات المطلوبة يرفع الجودة بشكل هائل. النموذج يتعلم النمط
        ويطبّقه بدقة أعلى بكثير من الوصف النظري.
      </P>

      <H2 id="constraints">٤. ضع قيوداً واضحة</H2>
      <UL>
        <li>«لا تتجاوز ٢٠٠ كلمة».</li>
        <li>«استخدم TypeScript فقط، لا JavaScript».</li>
        <li>«لا تستخدم مكتبات خارجية».</li>
        <li>«التزم بأسلوب Tailwind CSS».</li>
      </UL>

      <H2 id="format">٥. حدّد صيغة الإخراج</H2>
      <P>
        اطلب JSON، جدول Markdown، قائمة نقطية، أو نص عادي — بشكل صريح. هذا يجعل الإجابة قابلة
        للاستخدام مباشرة في تطبيقك أو تدفق عملك.
      </P>

      <H2 id="audience">٦. استهدف الجمهور</H2>
      <P>
        «اشرح كأنك تخاطب مبتدئاً» ينتج نصاً مختلفاً عن «اشرح لمهندس أنظمة موزّعة». حدّد المستوى
        دائماً.
      </P>

      <H2 id="iterate">٧. التحسين التكراري</H2>
      <P>
        الأمر الأول نادراً ما يكون مثالياً. راجع الإجابة، حدد ما ينقصها، وأعد الصياغة. اعتبر
        هذه الدورة جزءاً طبيعياً من العمل مع النموذج.
      </P>

      <H2 id="advanced">تقنيات متقدمة</H2>
      <H3>سلسلة الأفكار (Chain-of-Thought)</H3>
      <P>
        اطلب من النموذج «فكّر خطوة بخطوة» قبل الإجابة النهائية. هذا يحسّن دقة المسائل المنطقية
        والحسابية بشكل كبير.
      </P>
      <H3>التقسيم (Decomposition)</H3>
      <P>
        قسّم المهمة المعقدة إلى أوامر أصغر ومتسلسلة بدلاً من أمر عملاق واحد.
      </P>

      <H2 id="pitfalls">أخطاء شائعة</H2>
      <UL>
        <li>الغموض: «حسّن الكود» — حسّن كيف؟ للأداء؟ للقراءة؟</li>
        <li>الافتراض بأن النموذج «يعرف» ما لم يُذكر صراحةً.</li>
        <li>عدم التحقق من المخرجات، خصوصاً الأرقام والحقائق.</li>
      </UL>

      <H2 id="conclusion">الخلاصة</H2>
      <P>
        هندسة الأوامر مهارة قابلة للتعلّم والتحسين. الاستثمار فيها يعطي عائداً مضاعفاً في كل
        تفاعل مع الذكاء الاصطناعي. طبّق المبادئ الستة الأولى في أوامرك القادمة وستلاحظ فرقاً
        فورياً في جودة النتائج.
      </P>

      <H2 id="faq">أسئلة شائعة</H2>
      <H3>هل تختلف هندسة الأوامر بين النماذج؟</H3>
      <P>
        نعم، لكن المبادئ الأساسية متشابهة. كل نموذج له تفضيلات، لكن الوضوح والسياق يعملان مع
        الجميع.
      </P>
      <H3>هل ستختفي هذه المهارة مع تطوّر النماذج؟</H3>
      <P>
        القدرة على التعبير الدقيق عن الاحتياجات ستبقى قيّمة، حتى لو أصبحت النماذج أذكى.
      </P>
      <H3>ما أفضل مورد لتعلّمها؟</H3>
      <P>
        دليل OpenAI الرسمي، وثائق Anthropic، والتجربة العملية اليومية هي أفضل معلّم.
      </P>
    </>
  );
}

